public class MultiplicationTableOfFive {
    public static void main(String[] args){
        int num=5;
        for (int i=1; i<=10; i++)
        {
            int sum = num * i;
           System.out.println(num + "*" + i + " = " + sum);
        }
       //  System.out.println(num + "*" + i + " = " + sum);
    }
    
}
